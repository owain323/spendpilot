"""Two-phase benchmark for SpendPilot's detection engine.

Phase 1 (agent-visible): only case inputs are opened. The analysis runs and
predictions are SEALED to results/predictions.json.

Phase 2 (evaluation): gold labels are opened ONLY AFTER predictions are
sealed. There is no way to go back and change an answer.

Three evaluation sets, honestly labeled:

  default        the PUBLIC regression fixtures (benchmarks/cases.json +
                 gold/labels.json) — they ship with the repo, so they prove
                 "the engine matches its own regression cases", nothing more
  --independent  the INDEPENDENT hand-written suite
                 (benchmarks/independent/cases.json + gold/independent-labels.json)
                 — cases authored by hand against the decision rules
                 (threshold boundaries, split verdicts, cross-rule
                 interactions), NOT produced by any generator
  --derived      the DERIVED INVARIANCE SUITE (benchmarks/derived/,
                 generated by tools/make_derived.py, labels gitignored) —
                 mechanical rescale/rename/time-shift of the public fixtures.
                 A pass proves the judgments are INVARIANT under those
                 transformations. It is NOT generalization evidence: the
                 decision structures are identical by construction.

Usage:  python benchmarks/run.py                # public regression set
        python benchmarks/run.py --independent  # independent hand-written set
        python benchmarks/run.py --derived      # derived invariance suite
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from mcp_server import tools  # noqa: E402

BENCH = Path(__file__).resolve().parent
RESULTS = BENCH / "results"


def phase1_predict(cases_path: Path, results_path: Path) -> list[dict]:
    cases = json.loads(cases_path.read_text(encoding="utf-8"))
    predictions = []
    for case in cases["cases"]:
        # Agent-visible phase: only case inputs are opened.
        findings = tools.analyze_dataset(case["providers"], cases["months"])
        predictions.append({
            "case_id": case["id"],
            "flag": sorted(f["id"] for f in findings if f["verdict"] == "flag"),
            "keep": sorted(f["id"] for f in findings if f["verdict"] == "keep"),
            "hold": sorted(f["id"] for f in findings if f["verdict"] == "hold"),
            "confidence": {f["id"]: f.get("confidence") for f in findings},
        })
    results_path.parent.mkdir(exist_ok=True)
    results_path.write_text(
        json.dumps(predictions, indent=2), encoding="utf-8", newline="\n")
    return predictions


def phase2_score(predictions: list[dict], gold_path: Path,
                 basis: str, metrics_path: Path) -> dict:
    # Evaluation phase starts only after predictions are sealed.
    gold = json.loads(gold_path.read_text(encoding="utf-8"))

    tp = fp = fn = 0
    keep_correct = keep_missed = 0
    hold_correct = hold_missed = 0
    per_case = []
    for pred in predictions:
        g = gold[pred["case_id"]]
        pred_flag, gold_flag = set(pred["flag"]), set(g["flag"])
        tp += len(pred_flag & gold_flag)
        fp += len(pred_flag - gold_flag)
        fn += len(gold_flag - pred_flag)
        keep_ok = set(pred["keep"]) == set(g["keep"])
        hold_ok = set(pred["hold"]) == set(g["hold"])
        keep_correct += keep_ok
        keep_missed += not keep_ok
        hold_correct += hold_ok
        hold_missed += not hold_ok
        per_case.append({
            "case_id": pred["case_id"],
            "flag_ok": pred_flag == gold_flag,
            "keep_ok": keep_ok,
            "hold_ok": hold_ok,
            "extra_flags": sorted(pred_flag - gold_flag),
            "missed_flags": sorted(gold_flag - pred_flag),
        })

    metrics = {
        "cases": len(predictions),
        "flag_precision": round(tp / (tp + fp), 4) if tp + fp else None,
        "flag_recall": round(tp / (tp + fn), 4) if tp + fn else None,
        "flag_tp": tp, "flag_fp": fp, "flag_fn": fn,
        "keep_accuracy": round(keep_correct / len(predictions), 4),
        "hold_accuracy": round(hold_correct / len(predictions), 4),
        "cases_fully_correct": sum(1 for c in per_case if c["flag_ok"] and c["keep_ok"] and c["hold_ok"]),
        "per_case": per_case,
        "basis": basis,
    }
    metrics_path.write_text(json.dumps(metrics, indent=2), encoding="utf-8", newline="\n")
    return metrics


def main() -> int:
    if "--derived" in sys.argv:
        mode = "derived"
        cases_path = BENCH / "derived" / "cases.json"
        gold_path = BENCH / "derived" / "labels.json"
        metrics_path = RESULTS / "derived-metrics.json"
        basis = ("derived invariance suite: 24 cases mechanically derived from the "
                 "public fixtures (rescaled, renamed, time-shifted; seeded generator "
                 "tools/make_derived.py; labels kept out of the repo) — proves "
                 "invariance under transformation, NOT generalization")
    elif "--independent" in sys.argv:
        mode = "independent"
        cases_path = BENCH / "independent" / "cases.json"
        gold_path = BENCH / "gold" / "independent-labels.json"
        metrics_path = RESULTS / "independent-metrics.json"
        basis = ("independent hand-written suite: cases authored by hand against the "
                 "decision rules (threshold boundaries, split verdicts, cross-rule "
                 "interactions); not generator output; labels public in benchmarks/gold/")
    else:
        mode = "public"
        cases_path = BENCH / "cases.json"
        gold_path = BENCH / "gold" / "labels.json"
        metrics_path = RESULTS / "metrics.json"
        basis = ("public regression fixtures: 12 synthetic cases with planted "
                 "ground truth; sealed two-phase protocol")
    predictions_path = RESULTS / ("predictions.json" if mode == "public" else f"{mode}-predictions.json")
    predictions = phase1_predict(cases_path, predictions_path)
    metrics = phase2_score(predictions, gold_path, basis, metrics_path)
    print(f"set: {mode}")
    print(f"cases: {metrics['cases']}")
    print(f"flag precision: {metrics['flag_precision']}  recall: {metrics['flag_recall']}")
    print(f"keep accuracy: {metrics['keep_accuracy']}  hold accuracy: {metrics['hold_accuracy']}")
    print(f"cases fully correct: {metrics['cases_fully_correct']}/{metrics['cases']}")
    for case in metrics["per_case"]:
        if not (case["flag_ok"] and case["keep_ok"] and case["hold_ok"]):
            print(f"  MISMATCH {case['case_id']}: extra={case['extra_flags']} missed={case['missed_flags']}")
    ok = metrics["cases_fully_correct"] == metrics["cases"]
    print("BENCHMARK_" + ("OK" if ok else "FAIL"))
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
